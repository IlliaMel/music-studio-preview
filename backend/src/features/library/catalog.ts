const sections = [
  ['stations', ['Late Night Lo-fi', 'Ambient Spaces', 'Piano Room']],
  ['new', ['New This Week', 'Fresh Starts', 'After Hours']],
  ['top', ['Top 20', 'Electronic Mix', 'Acoustic Favorites']],
  ['rising', ['Rising', 'Tomorrow’s Sound', 'New Voices']],
  ['genres', ['Deep Focus', 'Jazz', 'Electronic', 'Ambient', 'Pop', 'Rock']],
  ['madeonstudio', ['Made on Studio', 'Sing Along', 'Night Drive']],
  ['remixes', ['Fresh Remixes', 'Reimagined', 'Second Take']],
  ['featured', ['Glass Harbor', 'Quiet Horizons', 'Warm Light']],
] as const
export const collections = sections.flatMap(([kind, names], sectionIndex) =>
  names.map((title, index) => ({
    id: `${kind}-${index}`,
    title,
    kind,
    isStation: kind === 'stations',
    trackIds: [
      ...catalogTracks.slice((sectionIndex + index) % catalogTracks.length),
      ...catalogTracks.slice(0, (sectionIndex + index) % catalogTracks.length),
    ].map((track) => track.id),
  })),
)
export const stations = collections
  .filter((collection) => collection.isStation)
  .map((station) => ({ ...station, live: true }))
