import com.illiamelnyk.studio.core.domain.track.MusicModel
import com.illiamelnyk.studio.core.domain.track.Track
import com.illiamelnyk.studio.core.domain.track.TrackId
import com.illiamelnyk.studio.core.domain.track.TrackRepository
import com.illiamelnyk.studio.core.domain.track.TrackStatus
import java.util.concurrent.ConcurrentHashMap
import java.util.concurrent.atomic.AtomicInteger
import kotlin.time.Clock
import kotlin.time.Duration
import kotlin.time.Duration.Companion.hours
import kotlin.time.Duration.Companion.minutes
import kotlin.time.Duration.Companion.seconds
import kotlin.time.Instant
import kotlinx.coroutines.CoroutineScope
import kotlinx.coroutines.Job
import kotlinx.coroutines.delay
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.MutableStateFlow
import kotlinx.coroutines.flow.asStateFlow
import kotlinx.coroutines.flow.distinctUntilChanged
import kotlinx.coroutines.flow.first
import kotlinx.coroutines.flow.map
import kotlinx.coroutines.flow.update
import kotlinx.coroutines.launch

/**
 * The user's tracks in memory, generated by a timer instead of the Music API: a new track composes
 * for [GENERATION_TIME] and becomes ready, unless its prompt names an artist ("in the style of …"),
 * which the service rejects after [REJECTION_TIME] with a suggestion. Every generation spends a
 * credit from [credits].
 *
 * @param scope runs the generations; they outlive the screen that started them, like jobs on the
 *   server. Tests pass a test scope and control the time.
 */
class FakeTrackRepository(
    private val credits: FakeCreditsRepository,
    private val sessions: SessionRepository,
    private val scope: CoroutineScope,
    private val clock: Clock,
) : TrackRepository {

    private val tracks = MutableStateFlow(seedTracks())
    private val requests = ConcurrentHashMap<TrackId, GenerationRequest>()
    private val generations = ConcurrentHashMap<TrackId, Job>()
    private val nextId = AtomicInteger(1)

    override fun observeMine(): Flow<List<Track>> = tracks.asStateFlow()

    override fun observeById(id: TrackId): Flow<Track?> =
        tracks.map { list -> list.find { it.id == id } }.distinctUntilChanged()

    override suspend fun create(request: GenerationRequest): Outcome<Track> {
        delay(FakeNetwork.latency)
        if (!credits.trySpend()) return Outcome.Failure(AppError.QuotaExceeded)
        val track = Track(
            id = TrackId("track-${nextId.getAndIncrement()}"),
            title = titleOf(request.prompt),
            artist = sessions.session.first()?.user?.displayName.orEmpty(),
            prompt = request.prompt,
            style = request.style,
            duration = request.duration,
            model = request.model,
            instrumental = request.instrumental,
            coverSeed = CoverSeed(request.prompt),
            status = TrackStatus.Generating(progress = 0f),
            createdAt = clock.now(),
            isLiked = false,
        )
        tracks.update { listOf(track) + it }
        startGeneration(track.id, request)
        return Outcome.Success(track)
    }

    override suspend fun retry(id: TrackId): Outcome<Track> {
        delay(FakeNetwork.latency)
        val track = tracks.value.find { it.id == id } ?: return Outcome.Failure(AppError.Unknown)
        // A second tap on Retry while the first one is already generating changes nothing.
        if (track.status !is TrackStatus.Failed) return Outcome.Success(track)
        if (!credits.trySpend()) return Outcome.Failure(AppError.QuotaExceeded)
        val request = requests[id] ?: GenerationRequest(track.prompt, track.duration, track.model)
        val generating = track.copy(status = TrackStatus.Generating(progress = 0f))
        replace(generating)
        startGeneration(id, request)
        return Outcome.Success(generating)
    }

    override suspend fun delete(id: TrackId): Outcome<Unit> {
        delay(FakeNetwork.latency)
        generations.remove(id)?.cancel()
        requests.remove(id)
        tracks.update { list -> list.filterNot { it.id == id } }
        return Outcome.Success(Unit)
    }

    override suspend fun setLiked(id: TrackId, liked: Boolean): Outcome<Unit> {
        delay(FakeNetwork.latency)
        tracks.update { list -> list.map { if (it.id == id) it.copy(isLiked = liked) else it } }
        return Outcome.Success(Unit)
    }

    private fun startGeneration(id: TrackId, request: GenerationRequest) {
        requests[id] = request
        generations[id] = scope.launch {
            if (request.prompt.contains(ARTIST_REFERENCE, ignoreCase = true)) {
                delay(REJECTION_TIME)
                updateStatus(id, TrackStatus.Failed(AppError.InvalidPrompt(suggestionFor(request.prompt))))
            } else {
                for (step in 1..GENERATION_STEPS) {
                    delay(GENERATION_TIME / GENERATION_STEPS)
                    val status = if (step == GENERATION_STEPS) {
                        TrackStatus.Ready
                    } else {
                        TrackStatus.Generating(step.toFloat() / GENERATION_STEPS)
                    }
                    updateStatus(id, status)
                }
            }
        }
    }

    private fun updateStatus(id: TrackId, status: TrackStatus) {
        tracks.update { list -> list.map { if (it.id == id) it.copy(status = status) else it } }
    }

    private fun replace(track: Track) {
        tracks.update { list -> list.map { if (it.id == track.id) track else it } }
    }

    companion object {
        val GENERATION_TIME = 8.seconds
        val REJECTION_TIME = 2.seconds

        /** Progress updates while composing: one a second. */
        private const val GENERATION_STEPS = 8
        private const val ARTIST_REFERENCE = "in the style of"
        private const val TITLE_LENGTH = 40

        /** The title the service would give: the start of the prompt. */
        private fun titleOf(prompt: String): String =
            prompt.trim().take(TITLE_LENGTH).trimEnd().replaceFirstChar { it.uppercaseChar() }

        /** The prompt with the artist replaced by a description of a sound, like the service suggests. */
        private fun suggestionFor(prompt: String): String {
            val start = prompt.indexOf(ARTIST_REFERENCE, ignoreCase = true)
            val end = prompt.indexOfAny(charArrayOf(',', '.'), startIndex = start).takeIf { it >= 0 } ?: prompt.length
            return prompt.replaceRange(start, end, "with an original sound of its own")
        }

        private fun seedTracks(): List<Track> = listOf(
            seed(1, "Rainy window lo-fi", "Lo-fi beat with soft rain and a warm Rhodes", 2.minutes, liked = true),
            seed(2, "Sunrise over the Carpathians", "Cinematic folk with violin and choir", 3.minutes + 30.seconds),
            seed(
                id = 3,
                title = "Song in the style of a famous band",
                prompt = "Indie rock song in the style of a famous band",
                duration = 2.minutes,
                status = TrackStatus.Failed(
                    AppError.InvalidPrompt("Indie rock song with an original sound of its own"),
                ),
            ),
            seed(4, "Neon tram", "Synthwave night ride with arpeggios", 2.minutes + 30.seconds, liked = true),
            seed(
                id = 5,
                title = "Morning coffee jazz",
                prompt = "Smooth jazz trio for a slow morning",
                duration = 1.minutes + 30.seconds,
                status = TrackStatus.Failed(AppError.Server),
            ),
            seed(6, "Kyiv after rain", "Ambient piano with city sounds", 4.minutes, model = MusicModel.V2),
        )

        private fun seed(
            id: Int,
            title: String,
            prompt: String,
            duration: Duration,
            status: TrackStatus = TrackStatus.Ready,
            liked: Boolean = false,
            model: MusicModel = MusicModel.V2_5,
        ) = Track(
            id = TrackId("seed-$id"),
            title = title,
            artist = SEED_ARTIST,
            prompt = prompt,
            style = null,
            duration = duration,
            model = model,
            instrumental = false,
            coverSeed = CoverSeed(title),
            status = status,
            // Made a day ago, one hour apart, newest first.
            createdAt = Instant.parse("2026-10-13T18:00:00Z") - (id - 1).hours,
            isLiked = liked,
        )

        /** The demo account's public name, which made the seed tracks. */
        private const val SEED_ARTIST = "Illia Melnyk"
    }
}
