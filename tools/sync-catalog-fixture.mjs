import { readFile, writeFile, mkdir } from 'node:fs/promises'

const root = new URL('../', import.meta.url)
const source = await readFile(new URL('public-fixtures/catalog-v1.json', root), 'utf8')
const document = JSON.parse(source)
const ids = document.tracks.map((track) => track.id)
if (document.schemaVersion !== 1 || new Set(ids).size !== ids.length) throw new Error('Invalid canonical track IDs')
for (const collection of document.collections) {
  if (new Set(collection.trackIds).size !== collection.trackIds.length || collection.trackIds.some((id) => !ids.includes(id))) {
    throw new Error('Invalid collection references: ' + collection.id)
  }
}
if (document.collections.find((item) => item.id === 'top-0').trackIds.length < 20) throw new Error('Top20 is incomplete')
const kotlin = 'package com.illiamelnyk.studio.core.data.demo\n\n' +
  '// Generated by tools/sync-catalog-fixture.mjs from public-fixtures/catalog-v1.json.\n' +
  'internal const val DEMO_PUBLIC_CATALOG_DOCUMENT = """\n' + source.trimEnd() + '\n"""\n'
const trackKotlin = [
  'package com.illiamelnyk.studio.core.data.demo', '',
  'import com.illiamelnyk.studio.core.domain.CoverSeed',
  'import com.illiamelnyk.studio.core.domain.track.MusicModel',
  'import com.illiamelnyk.studio.core.domain.track.Track',
  'import com.illiamelnyk.studio.core.domain.track.TrackId',
  'import com.illiamelnyk.studio.core.domain.track.TrackStatus',
  'import kotlin.time.Duration.Companion.milliseconds',
  'import kotlin.time.Instant', '',
  '// Generated by tools/sync-catalog-fixture.mjs from public-fixtures/catalog-v1.json.',
  'internal val PUBLIC_CATALOG_TRACKS: List<Track> = listOf(',
  ...document.tracks.flatMap((track) => [
    '    Track(',
    '        id = TrackId(' + JSON.stringify(track.id) + '),',
    '        title = ' + JSON.stringify(track.title) + ',',
    '        artist = ' + JSON.stringify(track.artist) + ',',
    '        prompt = "",', '        style = null,',
    '        duration = ' + track.durationMs + '.milliseconds,',
    '        model = MusicModel.V2_5,',
    '        instrumental = ' + track.instrumental + ',',
    '        coverSeed = CoverSeed(' + JSON.stringify(track.coverSeed) + '),',
    '        status = TrackStatus.Ready,',
    '        createdAt = Instant.parse(' + JSON.stringify(track.createdAt) + '),',
    '        isLiked = false,',
    '        genres = listOf(' + track.genres.map(JSON.stringify).join(', ') + '),',
    '    ),',
  ]), ')', '',
].join('\n')
const kinds = { stations: 'Stations', new: 'New', top: 'Top', rising: 'Rising', genres: 'Genres', madeonstudio: 'MadeOnStudio', remixes: 'Remixes', featured: 'Featured' }
const collectionKotlin = [
  'package com.illiamelnyk.studio.feature.listen.data.demo', '',
  'import com.illiamelnyk.studio.core.data.demo.PUBLIC_CATALOG_TRACKS',
  'import com.illiamelnyk.studio.core.domain.CoverSeed',
  'import com.illiamelnyk.studio.feature.listen.domain.CatalogCollection',
  'import com.illiamelnyk.studio.feature.listen.domain.CatalogSectionKind', '',
  '// Generated by tools/sync-catalog-fixture.mjs from public-fixtures/catalog-v1.json.',
  'internal val PUBLIC_CATALOG_COLLECTIONS: List<CatalogCollection> = listOf(',
  ...document.collections.flatMap((collection) => [
    '    CatalogCollection(',
    '        id = ' + JSON.stringify(collection.id) + ',',
    '        title = ' + JSON.stringify(collection.title) + ',',
    '        coverSeed = CoverSeed(' + JSON.stringify(collection.coverSeed) + '),',
    '        tracks = listOf(',
    ...collection.trackIds.map((id) => '            ' + JSON.stringify(id) + ','),
    '        ).map { id -> PUBLIC_CATALOG_TRACKS.first { it.id.value == id } },',
    '        isStation = ' + collection.isStation + ',',
    '        kind = CatalogSectionKind.' + kinds[collection.kind] + ',',
    '        trendSnapshotId = ' + JSON.stringify(collection.trendSnapshotId ?? null) + ',',
    '    ),',
  ]), ')', '',
].join('\n')
const outputs = new Map([
  ['backend/src/features/library/catalog.fixture.json', source],
  ['app/src/main/kotlin/com/illiamelnyk/studio/core/data/demo/PublicCatalogTracks.kt', trackKotlin],
  ['app/src/main/kotlin/com/illiamelnyk/studio/feature/listen/data/demo/PublicCatalogCollections.kt', collectionKotlin],
  ['app/src/main/assets/catalog/catalog-v1.json', source],
  ['app/src/main/kotlin/com/illiamelnyk/studio/core/data/demo/DemoPublicCatalogDocument.kt', kotlin],
])
for (const [relative, content] of outputs) {
  const target = new URL(relative, root)
  if (process.argv.includes('--check')) {
    if (await readFile(target, 'utf8') !== content) throw new Error('Catalog fixture drift: ' + relative)
  } else {
    await mkdir(new URL('./', target), { recursive: true })
    await writeFile(target, content)
  }
}
console.log('Canonical catalog ' + document.catalogVersion + ': ' + ids.length + ' tracks; ' + outputs.size + ' outputs synchronized')
